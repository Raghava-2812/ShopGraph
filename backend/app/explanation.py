"""
ShopGraph - Explanation Generator Module
app/explanation.py

This module converts structured Knowledge Graph signals (discovered graph edges,
shared features, shared use-cases, and category relationships) into clear,
human-readable explanation statements.

Key Value Proposition:
  Unlike opaque neural recommendations, every recommendation generated by ShopGraph
  is accompanied by specific, transparent justifications directly grounded in the
  underlying Knowledge Graph schema.
"""

from app.candidate_generator import CandidateInfo

# Friendly natural language display templates for Knowledge Graph relationship edges
_REL_LABELS: dict[str, str] = {
    "COMPATIBLE_WITH": "Directly compatible with the purchased product",
    "ACCESSORY":       "Accessory for the purchased product",
    "WORKS_WITH":      "Works with the purchased product",
    "SIMILAR_TO":      "Similar product to the one purchased",
}


def generate_reasons(
    purchased_product: str,
    candidate: CandidateInfo,
) -> list[str]:
    """Synthesize human-readable justification strings explaining a product recommendation.

    Evaluation Order:
      1. Direct Graph Relationships: States compatibility, accessory link, or similarity.
      2. Shared Features: Identifies shared hardware/software specifications.
      3. Shared Use Cases: Identifies common target workflows (gaming, office, etc.).
      4. Category Context: Identifies alternative options in the same category.
      5. Fallback: Asserts general relevance if specific signals are sparse.

    Args:
        purchased_product (str): Title of the reference or purchased product.
        candidate (CandidateInfo): Discovered candidate with associated graph signals.

    Returns:
        list[str]: Non-empty list of human-readable reason strings.
    """
    reasons: list[str] = []

    # 1. Direct relationship reasons (highest priority explanation)
    for rel in candidate.direct_relationships:
        label = _REL_LABELS.get(rel, f"Related via {rel}")
        reasons.append(label)

    # 2. Shared feature reasons (specific technical commonalities)
    for feature in candidate.shared_features:
        reasons.append(f"Shares {feature} feature with {purchased_product}")

    # 3. Shared use-case reasons (functional workflow overlap)
    for use_case in candidate.shared_use_cases:
        reasons.append(f"Useful for {use_case}")

    # 4. Same category — only add if not already explained by deeper graph edges
    if candidate.same_category and not reasons:
        reasons.append("In the same product category")

    # 5. Robust fallback: ensure at least one reason is always present
    if not reasons:
        reasons.append("Relevant product in the knowledge graph")

    return reasons

